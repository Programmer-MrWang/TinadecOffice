import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const evidence = join(process.cwd(), '.tinadec_dev/evidence/2026-10-10-interface-regression/graphseed-real');
const http = JSON.parse(await readFile(join(evidence, 'desktop-real-http-requests.json'), 'utf8'));
const installs = http.requests.filter(request => request.method === 'PUT');
assert.deepEqual(installs.map(request => request.status), [400, 201]);
assert.equal(installs[0].code, 'configuration_invalid');
assert.equal(installs[0].diagnostics[0].code, 'configuration_unique');
assert.match(installs[0].diagnostics[0].message, /agent_definitions/);
assert.equal(installs[0].trace_id_present, true);
assert.equal(installs[0].configuration_bytes_unchanged_on_failure, true);
assert.equal(installs[0].no_partial_installation_after_failure, true);
assert.equal(installs[0].category, 'user_action_required');
assert.equal(installs[0].retryable, false);
assert.ok(Array.isArray(installs[0].actions));
assert.match(installs[1].etag, /^"[0-9]+"$/);
const previews = http.requests.filter(request => request.path === '/api/v1/agent-packs/install-preview');
assert.ok(previews.length >= 3);
assert.ok(previews.every(request => request.status === 200 && request.etag));
const ui = JSON.parse(await readFile(join(evidence, 'desktop-ui-acceptance.json'), 'utf8'));
assert.match(ui.events[0].visible_details, /trace_id:/);
assert.equal(ui.events.find(event => event.step === 'ordinary_reconnect').no_auto_install, true);
assert.match(ui.events.find(event => event.step === 'inventory_content').text, /tinadec\.tests\.bootstrap-pack/);
assert.match(ui.events.find(event => event.step === 'inventory_content').text, /tinadec\.graph\.seed-pack/);
const current = JSON.parse(await readFile(join(evidence, 'current-config-read.json'), 'utf8'));
assert.equal(current.preview_action, 'up_to_date');
const restart = JSON.parse(await readFile(join(evidence, 'desktop-core-restart.json'), 'utf8'));
assert.equal(restart.real_core_process_restarted, true);
assert.equal(restart.workspace_defaults_unchanged, true);
const cas = JSON.parse(await readFile(join(evidence, 'real-cas-refusal.json'), 'utf8'));
assert.equal(cas.observed_status, 412);
assert.equal(cas.inventory_preserved_after_refusal, true);
const after = JSON.parse(await readFile(join(evidence, 'user-config-after.json'), 'utf8'));
assert.equal(after.unchanged, true);
const summary = { verified: true, exact_user_config_copy_readable: true, version: current.version, digest: current.digest, installation_requests: installs.length, install_outcomes: installs.map(request => request.status), failure_diagnostics: true, recovery_fields: true, no_partial_installation: true, validation_failure_toml_bytes_unchanged: true, ordinary_reconnect_no_auto_install: true, successful_etag: installs[1].etag, preview_etags: previews.map(request=>request.etag), configuration_failure_etag: installs[0].etag, cas_failure_etag: cas.error_etag, explicit_retry_single_request: true, core_restart_readable: true, defaults_unchanged_on_restart: true, user_toml_unchanged: true, boundary: 'Real Core/Gateway and repository Desktop components inside an isolated Electron window. HTTP host token injected only in owned server proxy; production main/preload and full App/installer are separate acceptance.' };
await writeFile(join(evidence, 'verification.json'), JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify(summary));
